#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
OPENVINO_PROJECT="speech_to_text_ubx330m"
GEMMA_PROJECT="speech_to_text_gemma4"
OPENVINO_COMPOSE="$PROJECT_DIR/data/ubx330m/compose.yaml"
GEMMA_COMPOSE="$PROJECT_DIR/compose.gemma4.yaml"
GEMMA_UBX_OVERRIDE="$PROJECT_DIR/compose.gemma4.ubx330m.yaml"
GEMMA_MICROPHONE_OVERRIDE="$PROJECT_DIR/compose.gemma4.microphone.yaml"
stopped_any=0

fail() {
  printf 'ERROR: %s\n' "$1" >&2
  exit 1
}

command -v docker >/dev/null 2>&1 || fail "Docker is required."
docker info >/dev/null 2>&1 || fail "Docker is unavailable to this user. Start Docker and grant this user access, then retry."

if (( EUID == 0 )) && [[ "${SUDO_UID:-}" =~ ^[0-9]+$ && "${SUDO_GID:-}" =~ ^[0-9]+$ ]]; then
  export APP_UID="${APP_UID:-$SUDO_UID}"
  export APP_GID="${APP_GID:-$SUDO_GID}"
else
  export APP_UID="${APP_UID:-$(id -u)}"
  export APP_GID="${APP_GID:-$(id -g)}"
fi
export AUDIO_GID="${AUDIO_GID:-1000}"

if [[ -f "$OPENVINO_COMPOSE" ]]; then
  grep -Fqx '# Managed by scripts/install_ubx330m.sh. Do not edit this file by hand.' "$OPENVINO_COMPOSE" \
    || fail "The OpenVINO Compose file is not installer-managed; refusing to stop that project."
  if [[ -n "$(docker compose -p "$OPENVINO_PROJECT" -f "$OPENVINO_COMPOSE" --project-directory "$PROJECT_DIR/data/ubx330m" ps -aq)" ]]; then
    docker compose -p "$OPENVINO_PROJECT" -f "$OPENVINO_COMPOSE" \
      --project-directory "$PROJECT_DIR/data/ubx330m" down
    stopped_any=1
  else
    printf 'No OpenVINO containers found for project %s.\n' "$OPENVINO_PROJECT"
  fi
elif [[ -n "$(docker ps --quiet --filter "label=com.docker.compose.project=$OPENVINO_PROJECT" --filter status=running)" ]]; then
  fail "The OpenVINO project is running but its installer Compose file is missing; refusing to guess how to stop it."
else
  printf 'OpenVINO Compose file is absent; skipping project %s.\n' "$OPENVINO_PROJECT"
fi

if [[ -f "$GEMMA_COMPOSE" && -f "$GEMMA_UBX_OVERRIDE" && -f "$GEMMA_MICROPHONE_OVERRIDE" ]]; then
  if [[ -n "$(docker compose -p "$GEMMA_PROJECT" \
    -f "$GEMMA_COMPOSE" \
    -f "$GEMMA_UBX_OVERRIDE" \
    -f "$GEMMA_MICROPHONE_OVERRIDE" ps -aq)" ]]; then
    docker compose -p "$GEMMA_PROJECT" \
      -f "$GEMMA_COMPOSE" \
      -f "$GEMMA_UBX_OVERRIDE" \
      -f "$GEMMA_MICROPHONE_OVERRIDE" down
    stopped_any=1
  else
    printf 'No Gemma containers found for project %s.\n' "$GEMMA_PROJECT"
  fi
elif [[ -n "$(docker ps --quiet --filter "label=com.docker.compose.project=$GEMMA_PROJECT" --filter status=running)" ]]; then
  fail "The Gemma project is running but its Compose files are incomplete; refusing to guess how to stop it."
else
  printf 'Gemma Compose files are incomplete; skipping project %s.\n' "$GEMMA_PROJECT"
fi

if (( stopped_any )); then
  printf '\nApplication containers stopped. Bind-mounted models and data/ubx330m/ were preserved.\n'
else
  printf '\nNo managed application containers were found; nothing was stopped.\n'
fi
